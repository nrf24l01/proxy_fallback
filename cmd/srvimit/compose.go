package main

import (
	"flag"
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/nrf24l01/proxy_fallback/internal/catalog"
)

// cmdCompose prints a docker compose file with one service per recorded
// snapshot, so the selection happens in the compose arguments:
//
//	docker compose up -d grafana     # start exactly one imitation
//	docker compose up -d             # start all of them
//	docker compose logs -f grafana
//	docker compose down
//
// Regenerate after recording new snapshots: srvimit compose > docker-compose.yml
func cmdCompose(args []string) error {
	fs := flag.NewFlagSet("compose", flag.ExitOnError)
	root := fs.String("fixtures", envOr("SRVIMIT_FIXTURES", "fixtures"), "snapshot directory to read service names from")
	basePort := fs.Int("base-port", 8000, "port of the first service; the rest follow in catalog order")
	bind := fs.String("bind", "127.0.0.1", "host bind address for published ports")
	image := fs.String("image", "ghcr.io/nrf24l01/proxy_fallback:latest", "image to run")
	_ = fs.Parse(args)

	return writeCompose(os.Stdout, *root, *basePort, *bind, *image)
}

func writeCompose(w io.Writer, root string, basePort int, bind, image string) error {
	list, err := catalog.Load(root)
	if err != nil {
		return err
	}
	sort.Slice(list, func(i, j int) bool { return list[i].Name < list[j].Name })

	fmt.Fprintf(w, `# Generated by srvimit compose from the snapshots in %s.
#
#   docker compose up -d <service>   # start exactly one imitation, e.g.: docker compose up -d grafana
#   docker compose up -d             # start every service in this file
#   docker compose logs -f <service>
#   docker compose down
#
# The published image already contains the snapshots, so no volume mounts are
# needed. Regenerate after re-recording: srvimit compose > docker-compose.yml
name: srvimit

services:
`, root)

	parts := make([]string, 0, len(list))
	for i, e := range list {
		port := basePort + i
		fmt.Fprintf(w, `  %[1]s:
    image: %[2]s
    build:
      context: .
      args:
        VERSION: local
    container_name: srvimit-%[1]s
    restart: unless-stopped
    command: ["serve", "-service", "%[1]s", "-port", "%[3]d", "-listen", "0.0.0.0"]
    ports:
      - "%[4]s:%[3]d:%[3]d"
    read_only: true
    tmpfs:
      - /tmp
    security_opt:
      - no-new-privileges:true
    healthcheck:
      test: ["CMD", "wget", "-q", "--spider", "http://127.0.0.1:%[3]d/"]
      interval: 30s
      timeout: 5s
      retries: 3
      start_period: 5s

`, e.Name, image, port, bind)
		parts = append(parts, fmt.Sprintf("%s=%d", e.Name, port))
	}
	fmt.Fprintf(w, "# ports: %s\n", strings.Join(parts, " "))
	return nil
}
